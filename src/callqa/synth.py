@dataclass
class Turn:
    speaker: str  # "agent" or "customer"
    text: str


@dataclass
class Call:
    call_id: str
    officer: str
    officer_voice: str
    customer: str
    customer_voice: str
    campaign: str
    started_at: str
    outcome: str
    steps: dict[str, bool]  # for conversations: every applicable step, covered or not
    flags: list[str]
    personal: list[dict[str, str]]  # {"kind", "value"} planted in the contact's lines
    turns: list[Turn] = field(default_factory=list)

    def to_json(self) -> dict:
        return asdict(self)

    @classmethod
    def from_json(cls, data: dict) -> "Call":
        return cls(**{**data, "turns": [Turn(**turn) for turn in data["turns"]]})


def _spoken_digits(number: str) -> str:
    return " ".join(number)


def _conversation(rng: random.Random, call: Call, steps: list[str], fields: dict) -> None:
    """Fill ``call.turns`` for a full conversation that matches ``call.steps`` and flags."""

    def say(speaker: str, text: str) -> None:
        call.turns.append(Turn(speaker, text.format(**fields)))

    def exchange(officer_line: str | None, contact_line: str | None) -> None:
        if officer_line is None:
            return
        if officer_line.startswith("CUSTOMER:"):  # the contact speaks first
            say("customer", officer_line.removeprefix("CUSTOMER:"))
            say("agent", contact_line)
            return
        say("agent", officer_line)
        if contact_line:
            say("customer", contact_line)

    purpose = f"purpose_{call.campaign}"
    violations = list(call.flags)
    trap = rng.choice(TRAPS) if rng.random() < 0.45 else None
    personal = list(call.personal)

    for step in steps:
        bank = COVERED if call.steps[step] else SKIPPED
        key = purpose if step == "purpose" else step
        exchange(*rng.choice(bank[key]))

        if step == "qualify_credit":  # the middle of the call, where selling happens
            for flag in violations:
                say("agent", rng.choice(VIOLATIONS[flag]))
                say("customer", rng.choice(["Hmm, okay.", "Is that so?", "Well, alright."]))
            if trap:
                if trap[0]:
                    say("customer", trap[0])
                say("agent", trap[1])
            for item in personal:
                say("customer", item["spoken"])
                say("agent", SSN_REPLY if item["kind"] == "ssn" else "Thank you, I've noted that.")


def _short_call(rng: random.Random, call: Call, fields: dict) -> None:
    def say(speaker: str, text: str) -> None:
        call.turns.append(Turn(speaker, text.format(**fields)))

    greeting = rng.choice(COVERED["greeting_identify"])[0]
    if call.outcome == "voicemail":
        say("customer", "Hi, you've reached {first}. I can't come to the phone right now. Please leave a message after the tone.")  # fmt: skip
        say(
            "agent",
            rng.choice(
                [
                    "Hi {first}, this is {agent} from {company}. I'm calling about home loan options. Please call me back at {callback}. Thank you.",
                    "Hi {first}, it's {agent} with {company}. I'll try you again later.",
                ]
            ),
        )
        return
    say("customer", "Hello?")
    say("agent", greeting)
    if call.outcome == "wrong_number":
        say("customer", rng.choice(["I think you have the wrong number. Nobody named {first} lives here.", "Who? No, you have the wrong number."]))  # fmt: skip
        say("agent", "I'm sorry about that. I'll update our records. Have a good day.")
    elif call.outcome == "declined_early":
        say("customer", rng.choice(["I'm not interested. Please don't call again.", "No thanks. Take me off your list."]))  # fmt: skip
        say("agent", "Understood. I'll remove you from our list. Have a good day.")
    else:  # callback_requested
        say("customer", rng.choice(["I'm at work right now. Can you call me back after six?", "This isn't a good time. Try me tomorrow morning."]))  # fmt: skip
        say("agent", "Of course, I'll call you then. Thanks, {first}.")


def generate(
    count: int = 160, seed: int = 11, start: datetime = datetime(2026, 11, 2, 9, 0)
) -> list[Call]:
    """``count`` calls spread over two working weeks, the same for the same seed."""
    from callqa.rubric import Rubric

    rubric = Rubric.load()
    rng = random.Random(seed)
    calls: list[Call] = []
    for index in range(count):
        name, nmls, voice, cover_odds, violation_odds = OFFICERS[index % len(OFFICERS)]
        first, last = rng.choice(CUSTOMERS)
        campaign = "cold" if rng.random() < 0.6 else "warm"
        odds = OUTCOME_ODDS[campaign]
        outcome = rng.choices(list(odds), list(odds.values()))[0]
        day = start + timedelta(days=rng.choice([0, 1, 2, 3, 4, 7, 8, 9, 10, 11]))
        started = day + timedelta(minutes=rng.randint(0, 8 * 60))
        d2 = f"{rng.randint(10, 99)}"
        fields = {
            "first": first,
            "agent": name,
            "company": COMPANY,
            "nmls": _spoken_digits(nmls),
            "state": rng.choice(STATES),
            "callback": f"5 5 5, 0 1 {_spoken_digits(str(60 + index % 30))}",
            "first_lower": first.lower(),
            "last_lower": last.lower(),
            "d2": _spoken_digits(d2),
            "d2c": d2,
            "day": rng.randint(2, 27),
            "yy": rng.randint(60, 95),
        }
        call = Call(
            call_id=f"call_{index + 1:03d}",
            officer=name,
            officer_voice=voice,
            customer=f"{first} {last}",
            customer_voice=rng.choice(CUSTOMER_VOICES),
            campaign=campaign,
            started_at=started.isoformat(timespec="minutes"),
            outcome=outcome,
            steps={},
            flags=[],
            personal=[],
        )
        if outcome == "conversation":
            steps = [step.id for step in rubric.steps_for(campaign)]
            call.steps = {
                step: rng.random() < cover_odds.get(step, cover_odds["*"]) for step in steps
            }
            call.flags = [flag for flag, chance in violation_odds.items() if rng.random() < chance]
            for kind, spoken, value in PERSONAL:
                if rng.random() < 0.18:
                    call.personal.append(
                        {
                            "kind": kind,
                            "spoken": spoken.format(**fields),
                            "value": value.format(**fields),
                        }
                    )
            _conversation(rng, call, steps, fields)
        else:
            _short_call(rng, call, fields)
        calls.append(call)
    return calls
